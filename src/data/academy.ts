interface DrillBase {
  id: string
  fen: string
  prompt: string
  hint: string
  explanation: string
}
export interface MoveDrill extends DrillBase {
  kind: 'move'
  line: string[]
  alternatives?: string[]
  goal?: 'mate' | 'safe-knight' | 'check'
}
export interface ChoiceDrill extends DrillBase {
  kind: 'choice'
  options: { text: string; feedback: string }[]
  answer: number
}
export type Drill = MoveDrill | ChoiceDrill
export interface Lesson {
  id: string
  skill: Skill
  title: string
  summary: string
  minutes: number
  ideas: string[]
  habit: string
  drills: Drill[]
}

/** Small original teaching positions, not copied from a puzzle collection. */
export function position(pieces: string, turn = 'w', rights = '-'): string {
  const squares = new Map(pieces.split(' ').map((p) => [p.slice(1), p[0]]))
  const ranks = []
  for (let r = 8; r >= 1; r--) {
    let row = ''
    let empty = 0
    for (const file of 'abcdefgh') {
      const piece = squares.get(`${file}${r}`)
      if (piece) {
        if (empty) row += empty
        empty = 0
        row += piece
      } else empty++
    }
    if (empty) row += empty
    ranks.push(row)
  }
  return `${ranks.join('/')} ${turn} ${rights} - 0 1`
}
function after(moves: string) {
  const board = new Chess()
  for (const move of moves.split(' ')) board.move(move)
  return board.fen()
}
const m = (
  id: string,
  fen: string,
  prompt: string,
  line: string[],
  hint: string,
  explanation: string,
  extra: Partial<MoveDrill> = {},
): MoveDrill => ({ kind: 'move', id, fen, prompt, line, hint, explanation, ...extra })
const q = (
  id: string,
  fen: string,
  prompt: string,
  options: [string, string][],
  answer: number,
  explanation: string,
): ChoiceDrill => ({
  kind: 'choice',
  id,
  fen,
  prompt,
  hint: 'Посмотрите на нападения, защитников и возможный ответ соперника.',
  explanation,
  options: options.map(([text, feedback]) => ({ text, feedback })),
  answer,
})

const textFlip = (text: string) => text.replace(/\b([a-h])([1-8])\b/g, (_, f: string, r: string) => f + (9 - Number(r)))
/** Reflect ranks and swap colours: the same skill must also work with Black. */
export function mirrorDrill(drill: MoveDrill): MoveDrill {
  const flipSquare = (s: string) => s[0] + (9 - Number(s[1]))
  const source = new Chess(drill.fen)
  const pieces = source
    .board()
    .flat()
    .filter((p) => p !== null)
    .map((p) => (p.color === 'w' ? p.type : p.type.toUpperCase()) + flipSquare(p.square))
    .join(' ')
  const rights = drill.fen
    .split(' ')[2]
    .replace(/[KQkq]/g, (s) => (s === s.toUpperCase() ? s.toLowerCase() : s.toUpperCase()))
  const fen = position(
    pieces,
    source.turn() === 'w' ? 'b' : 'w',
    rights === '-' ? '-' : [...rights].sort((a, b) => 'KQkq'.indexOf(a) - 'KQkq'.indexOf(b)).join(''),
  )
  const target = new Chess(fen)
  const line = drill.line.map((san) => {
    const move = source.move(san)
    return target.move({ from: flipSquare(move.from), to: flipSquare(move.to), promotion: move.promotion }).san
  })
  const alternatives = drill.alternatives?.map((san) => {
    const move = new Chess(drill.fen).move(san)
    return new Chess(fen).move({ from: flipSquare(move.from), to: flipSquare(move.to), promotion: move.promotion }).san
  })
  return {
    ...drill,
    id: drill.id + '-black',
    fen,
    line,
    alternatives,
    prompt: textFlip(drill.prompt),
    hint: textFlip(drill.hint),
    explanation: textFlip(drill.explanation),
  }
}

